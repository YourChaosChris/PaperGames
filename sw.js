function hexOf(buffer) {
  const bytes = new Uint8Array(buffer);
  let out = "";
  for (let i = 0; i < bytes.length; i++) out += (bytes[i] < 16 ? "0" : "") + bytes[i].toString(16);
  return out;
}

// Resolves to true when resp's body has the given short checksum. Without
// crypto.subtle (very old browsers) nothing can be checked, so the file is
// downloaded instead.
function hasHash(resp, hash) {
  if (!hash || !self.crypto || !self.crypto.subtle) return Promise.resolve(false);
  return resp.clone().arrayBuffer()
    .then((buf) => self.crypto.subtle.digest("SHA-1", buf))
    .then((digest) => hexOf(digest).slice(0, 8) === hash)
    .catch(() => false);
}

function isStorageError(err) {
  return !!err && (err.name === "QuotaExceededError" || err.code === 22);
}

let installProgress = null;
let lastProgressPost = 0;

function postProgress(force) {
  const now = Date.now();
  if (!force && now - lastProgressPost < 1000) return Promise.resolve();
  lastProgressPost = now;
  const msg = { papergamesInstall: Object.assign({ version: CACHE_NAME }, installProgress) };
  return self.clients.matchAll({ type: "window", includeUncontrolled: true })
    .then((list) => list.forEach((client) => client.postMessage(msg)))
    .catch(() => { /* no pages to tell */ });
}

// The languages other than English whose texts an older version of the
// app stored on this device (as an array of language codes).
function storedTextLanguages(oldCaches) {
  return Promise.all(oldCaches.map((c) => c.keys().catch(() => [])))
    .then((lists) => {
      const found = {};
      lists.forEach((list) => list.forEach((req) => {
        const m = /\/text\/([a-z]{2})\//.exec(req.url);
        if (m && m[1] !== "en") found[m[1]] = true;
      }));
      return Object.keys(found);
    });
}

function installShell() {
  installProgress = { done: 0, total: APP_SHELL.length };
  let cache, oldCaches = [], keepLangs = [];
  return caches.keys()
    .then((keys) => Promise.all(keys
      .filter((key) => key !== CACHE_NAME && key.indexOf(CACHE_PREFIX) === 0)
      .map((key) => caches.open(key))))
    .then((list) => { oldCaches = list; return storedTextLanguages(oldCaches); })
    .then((langs) => { keepLangs = langs; return caches.open(CACHE_NAME); })
    .then((c) => {
      cache = c;
      const queue = APP_SHELL.slice();
      // Languages stored by the version before come along (their files are
      // copied from there when unchanged, see fromOldCaches).
      TEXT_LAZY.forEach((url) => { if (keepLangs.indexOf(url.split("/")[1]) !== -1) queue.push(url); });
      installProgress.total = queue.length;
      const failed = [];
      let storageError = null;

      function fromOldCaches(url, i) {
        if (i >= oldCaches.length) return Promise.resolve(false);
        return oldCaches[i].match(url).then((resp) => {
          if (!resp || !resp.ok) return fromOldCaches(url, i + 1);
          return hasHash(resp, FILE_HASHES[url]).then((same) =>
            same ? cache.put(url, resp).then(() => true) : fromOldCaches(url, i + 1));
        });
      }
      function download(url, triesLeft) {
        return fetch(new Request(url, { cache: "no-cache" }))
          .then((resp) => {
            if (!resp || !resp.ok) throw new Error("HTTP " + (resp && resp.status));
            return cache.put(url, resp);
          })
          .catch((err) => {
            if (isStorageError(err) || triesLeft <= 1) throw err;
            return new Promise((r) => setTimeout(r, 1000)).then(() => download(url, triesLeft - 1));
          });
      }
      function one(url) {
        return cache.match(url)
          .then((have) => have || fromOldCaches(url, 0).then((copied) => copied || download(url, INSTALL_TRIES)))
          .then(() => { installProgress.done++; postProgress(false); })
          .catch((err) => {
            if (isStorageError(err)) storageError = err;
            failed.push(url);
          });
      }
      function worker() {
        if (storageError || !queue.length) return Promise.resolve();
        return one(queue.shift()).then(worker);
      }
      postProgress(true);
      const workers = [];
      for (let i = 0; i < INSTALL_PARALLEL; i++) workers.push(worker());
      return Promise.all(workers).then(() => {
        if (storageError) {
          installProgress.error = "storage";
          return postProgress(true).then(() => { throw storageError; });
        }
        if (failed.length) {
          installProgress.error = "network";
          return postProgress(true).then(() => { throw new Error("not stored: " + failed.join(", ")); });
        }
        return postProgress(true);
      });
    });
}

self.addEventListener("install", (event) => {
  event.waitUntil(installShell().then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  if (new URL(req.url).origin !== self.location.origin) return; // let Lichess calls pass through untouched

  // Stale-while-revalidate: answer immediately from cache when we have it
  // (fast, works offline), but always also fetch from the network in the
  // background and refresh the cache for next time. Plain cache-first would
  // otherwise serve the exact same files forever after every future deploy,
  // until the CACHE_NAME below happens to get bumped by hand. (Since v256
  // this applies only to files NOT in FILE_HASHES; those are served as
  // stored, see below.)
  //
  // { cache: "no-cache" } is required here: GitHub Pages sends
  // Cache-Control: max-age=600, so a plain fetch(req) can be silently
  // answered by the browser's own HTTP cache for up to 10 minutes,
  // never reaching the network at all. no-cache revalidates with the
  // server while still allowing an unchanged response to return 304.
  //
  // page.html?lang=xx is page.html shown in another language (the page picks
  // the language itself, see tools/seo.js): all of them share the cache
  // entry of page.html, so they open offline too and the cache doesn't fill
  // up with twelve copies of every page.
  const url = new URL(req.url);
  const langPage = /[?&]lang=/.test(url.search);
  const key = langPage ? url.origin + url.pathname : req;
  event.respondWith(
    caches.open(CACHE_NAME).then((cache) =>
      cache.match(key, langPage ? { ignoreSearch: true } : undefined).then((cached) => {
        // Files in FILE_HASHES (scripts, styles AND pages) are immutable for
        // this worker version: a new worker gets a new cache after its
        // install-time hash checks. Serve those directly from Cache Storage,
        // including offline, and never refresh them from the network: a page
        // refreshed on its own (new HTML) over the scripts of this version,
        // with the update itself broken off by a network failure, left a
        // mixed copy that did not react (report of 19.10.2026, task 99w).
        // The name is the path below the worker's folder (lang/de.js,
        // css/chess.css, text/de/chess.js, ...), as FILE_HASHES lists it;
        // the folder itself is "./".
        const scopePath = new URL(self.registration.scope).pathname;
        let assetName = url.pathname.indexOf(scopePath) === 0 ? url.pathname.slice(scopePath.length) : url.pathname.replace(/^.*\//, "");
        if (assetName === "") assetName = "./";
        if (cached && FILE_HASHES[assetName]) return cached;

        const networkUpdate = fetch(req, { cache: "no-cache" })
          .then((resp) => {
            if (resp && resp.ok) {
              cache.put(key, resp.clone());
            }
            return resp;
          })
          .catch(() => cached || (req.mode === "navigate" ? cache.match("index.html") : undefined));

        return cached || networkUpdate;
      })
    )
  );
});

// The settings dialog asks which version is running; CACHE_NAME is the
// only place the version is kept. A page opened while this worker is still
// installing asks how far the install is.
// Stores the rules and history texts of one language (all games), so they
// open offline. Best effort: a file that does not load is simply left out
// (the page then shows the English text), nothing is retried here; the page
// asks again on its next visit. Progress goes to the pages as
// { papergamesText: { lang, done, total, finished } }.
const textRuns = {};

function postText(info) {
  return self.clients.matchAll({ type: "window", includeUncontrolled: true })
    .then((list) => list.forEach((client) => client.postMessage({ papergamesText: info })))
    .catch(() => { /* no pages to tell */ });
}

function storeTextLanguage(lang) {
  if (!/^[a-z]{2}$/.test(lang) || lang === "en") return Promise.resolve();
  if (textRuns[lang]) return textRuns[lang];
  const files = TEXT_LAZY.filter((k) => k.indexOf("text/" + lang + "/") === 0);
  if (!files.length) return Promise.resolve();
  textRuns[lang] = caches.open(CACHE_NAME).then((cache) => {
    const queue = files.slice();
    let done = 0, stop = false;
    function one(url) {
      return cache.match(url).then((have) => have || fetch(new Request(url, { cache: "no-cache" })).then((resp) => {
        if (!resp || !resp.ok) throw new Error("HTTP " + (resp && resp.status));
        return cache.put(url, resp);
      })).then(() => { done++; }).catch((err) => { if (isStorageError(err)) stop = true; });
    }
    function worker() {
      if (stop || !queue.length) return Promise.resolve();
      return one(queue.shift()).then(worker);
    }
    const workers = [];
    for (let i = 0; i < TEXT_PARALLEL; i++) workers.push(worker());
    return Promise.all(workers).then(() => postText({ lang: lang, done: done, total: files.length, finished: true }));
  }).catch(() => { /* no cache to fill */ }).then(() => {
    // Done (or given up): the next ask checks again and fetches what is
    // still missing.
    delete textRuns[lang];
  });
  return textRuns[lang];
}

self.addEventListener("message", (event) => {
  if (!event.source) return;
  if (event.data && typeof event.data === "object" && typeof event.data.papergamesTextLang === "string") {
    event.waitUntil(storeTextLanguage(event.data.papergamesTextLang));
    return;
  }
  if (event.data === "papergames-version") {
    event.source.postMessage({ papergamesVersion: CACHE_NAME });
  } else if (event.data === "papergames-progress" && installProgress) {
    event.source.postMessage({ papergamesInstall: Object.assign({ version: CACHE_NAME }, installProgress) });
  }
});
